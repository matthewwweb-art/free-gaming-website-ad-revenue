-- Matthew Web / Free Game Hub community chat - PRIVATE BETA database setup.
-- Run ONCE in Supabase SQL Editor after reviewing it. Uses authenticated email sign-in.
-- Messages are publicly readable; posting requires login and a self-attested 18+ profile.
-- Never expose a Supabase secret/service_role key to the browser.

create table if not exists public.community_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.community_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select auth.uid() is not null and exists (
    select 1 from public.community_admins where user_id = auth.uid()
  );
$$;
revoke all on function public.community_is_admin() from public;
grant execute on function public.community_is_admin() to authenticated;

create table if not exists public.community_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (
    char_length(display_name) between 2 and 24
    and display_name ~ '^[A-Za-z0-9 _-]+$'
  ),
  adult_attested boolean not null check (adult_attested = true),
  created_at timestamptz not null default now()
);

create table if not exists public.community_bans (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.community_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  display_name text not null,
  body text not null check (char_length(body) between 1 and 350),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists community_messages_recent on public.community_messages(created_at desc);
create index if not exists community_messages_by_author on public.community_messages(user_id, created_at desc);

create table if not exists public.community_reports (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.community_messages(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  reason text not null check (char_length(reason) between 3 and 160),
  created_at timestamptz not null default now(),
  unique(message_id, reporter_id)
);

-- Trigger is SECURITY DEFINER so the browser cannot forge an admin badge,
-- bypass the profile, or alter user IDs. Advisory lock prevents parallel rate-limit bypass.
create or replace function public.community_before_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  nickname text;
begin
  new.user_id := auth.uid();
  if new.user_id is null then raise exception 'Sign in before posting'; end if;
  perform pg_advisory_xact_lock(hashtext(new.user_id::text));
  if exists (select 1 from public.community_bans where user_id = new.user_id) then
    raise exception 'This account cannot post to chat';
  end if;
  select display_name into nickname
    from public.community_profiles
    where user_id = new.user_id and adult_attested = true;
  if nickname is null then raise exception 'Complete your 18+ chat profile first'; end if;
  new.display_name := nickname;
  new.is_admin := exists (select 1 from public.community_admins where user_id = new.user_id);
  new.body := btrim(new.body);
  if char_length(new.body) < 1 or char_length(new.body) > 350 then
    raise exception 'Messages must be 1 to 350 characters';
  end if;
  if new.body ~* '(https?://|www[.]|[[:alnum:]_.+-]+@[[:alnum:].-]+[.][[:alpha:]]{2,})' then
    raise exception 'Links and email addresses are not allowed';
  end if;
  if exists (
    select 1 from public.community_messages
    where user_id = new.user_id and created_at > now() - interval '12 seconds'
  ) then
    raise exception 'Please wait 12 seconds between messages';
  end if;
  new.created_at := now();
  return new;
end;
$$;

drop trigger if exists community_message_before_insert on public.community_messages;
create trigger community_message_before_insert
before insert on public.community_messages for each row
execute function public.community_before_insert();

-- RLS and explicit minimal privileges for the browser.
alter table public.community_admins enable row level security;
alter table public.community_profiles enable row level security;
alter table public.community_bans enable row level security;
alter table public.community_messages enable row level security;
alter table public.community_reports enable row level security;

revoke all on public.community_admins from anon, authenticated;
revoke all on public.community_profiles from anon, authenticated;
revoke all on public.community_bans from anon, authenticated;
revoke all on public.community_messages from anon, authenticated;
revoke all on public.community_reports from anon, authenticated;

grant select, insert(user_id, display_name, adult_attested), update(display_name, adult_attested)
  on public.community_profiles to authenticated;
grant select on public.community_messages to anon, authenticated;
grant insert(body), delete on public.community_messages to authenticated;
grant select on public.community_reports to authenticated;
grant insert(message_id, reason) on public.community_reports to authenticated;
grant select, insert(user_id), delete on public.community_bans to authenticated;
grant usage, select on sequence public.community_messages_id_seq to authenticated;
grant usage, select on sequence public.community_reports_id_seq to authenticated;

-- Profiles are private: only the logged-in owner can read/change theirs.
drop policy if exists community_profiles_read_self on public.community_profiles;
create policy community_profiles_read_self on public.community_profiles
  for select to authenticated using (user_id = auth.uid());
drop policy if exists community_profiles_insert_self on public.community_profiles;
create policy community_profiles_insert_self on public.community_profiles
  for insert to authenticated with check (
    user_id = auth.uid() and adult_attested = true and
    (display_name !~* '(matthew|moderator|admin|staff|support|official)' or public.community_is_admin())
  );
drop policy if exists community_profiles_update_self on public.community_profiles;
create policy community_profiles_update_self on public.community_profiles
  for update to authenticated using (user_id = auth.uid()) with check (
    user_id = auth.uid() and adult_attested = true and
    (display_name !~* '(matthew|moderator|admin|staff|support|official)' or public.community_is_admin())
  );

-- Read-only access to public messages for guests. Authenticated users post via the validated trigger.
drop policy if exists community_messages_read_all on public.community_messages;
create policy community_messages_read_all on public.community_messages
  for select to anon, authenticated using (true);
drop policy if exists community_messages_post on public.community_messages;
create policy community_messages_post on public.community_messages
  for insert to authenticated with check (user_id = auth.uid() and not exists (
    select 1 from public.community_bans where user_id = auth.uid()
  ));
drop policy if exists community_messages_admin_delete on public.community_messages;
create policy community_messages_admin_delete on public.community_messages
  for delete to authenticated using (public.community_is_admin());

-- Reports are only visible to admins. Members can report messages once each.
drop policy if exists community_reports_admin_read on public.community_reports;
create policy community_reports_admin_read on public.community_reports
  for select to authenticated using (public.community_is_admin());
drop policy if exists community_reports_member_insert on public.community_reports;
create policy community_reports_member_insert on public.community_reports
  for insert to authenticated with check (reporter_id = auth.uid());

-- Bans: members can check their own status; admins can inspect and manage bans.
drop policy if exists community_bans_read on public.community_bans;
create policy community_bans_read on public.community_bans
  for select to authenticated using (user_id = auth.uid() or public.community_is_admin());
drop policy if exists community_bans_admin_insert on public.community_bans;
create policy community_bans_admin_insert on public.community_bans
  for insert to authenticated with check (public.community_is_admin());
drop policy if exists community_bans_admin_delete on public.community_bans;
create policy community_bans_admin_delete on public.community_bans
  for delete to authenticated using (public.community_is_admin());

-- Postgres Changes: fine for a small initial room; Broadcast is preferable later at scale.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'community_messages'
  ) then
    alter publication supabase_realtime add table public.community_messages;
  end if;
end $$;

